<?php

namespace ThalysJuvenal\FilamentAnimalia\Scripts;

use RuntimeException;

/**
 * Regenerates resources/tokens/animalia.php from local clones of the
 * upstream AnimaliaDS repositories (Style Dictionary JSON files).
 */
class SyncTokens
{
    private const HEADER = '// Generated by scripts/sync-tokens — do not edit by hand.';

    public function __construct(
        private readonly string $brandPath,
        private readonly string $designTokensPath,
    ) {}

    /**
     * @return array<string, array<string, mixed>>
     */
    public function build(): array
    {
        $brand = fn (string $file): array => $this->read($this->brandPath, "src/tokens/colors/{$file}.json");
        $design = fn (string $file): array => $this->read($this->designTokensPath, "src/{$file}.json");

        $neutral = [];
        foreach (['light', 'mid', 'dark'] as $tone) {
            $neutral += $this->leaves($brand("neutral/{$tone}"), ['color', 'neutral', $tone]);
        }

        $color = [
            'brand-01' => $this->leaves($brand('brand/brand-01'), ['color', 'brand-01']),
            'brand-02' => $this->leaves($brand('brand/brand-02'), ['color', 'brand-02']),
            'neutral' => $neutral,
        ];

        foreach (['positive', 'negative', 'warning', 'info'] as $family) {
            $color[$family] = $this->leaves($design("colors/feedback/{$family}"), ['color', 'feedback', $family]);
        }

        $shadow = $this->leaves($design('shadow/index'), ['shadow']);
        unset($shadow['none']);

        return [
            'source' => [
                'animalia-brand' => $this->revision($this->brandPath),
                'animalia-design-tokens' => $this->revision($this->designTokensPath),
            ],
            'color' => $color,
            'radius' => $this->leaves($design('border/radius'), ['border', 'radius']),
            'border-width' => $this->leaves($design('border/width'), ['border', 'width']),
            'spacing' => $this->leaves($design('spacing/index'), ['spacing']),
            'squish' => $this->leaves($design('spacing/squish'), ['spacing', 'squish']),
            'shadow' => $shadow,
        ];
    }

    public function write(string $target): void
    {
        $tokens = $this->build();

        $lines = ['<?php', '', self::HEADER, 'return ['];

        foreach ($tokens as $name => $group) {
            $key = var_export($name, true);

            if ($name === 'source' || $name === 'shadow') {
                $lines[] = "    {$key} => [";
                foreach ($group as $item => $value) {
                    $lines[] = '        '.var_export((string) $item, true).' => '.var_export($value, true).',';
                }
                $lines[] = '    ],';
            } elseif ($name === 'color') {
                $lines[] = "    {$key} => [";
                foreach ($group as $family => $shades) {
                    $lines[] = '        '.var_export((string) $family, true).' => '.$this->inline($shades).',';
                }
                $lines[] = '    ],';
            } else {
                $lines[] = "    {$key} => ".$this->inline($group).',';
            }
        }

        $lines[] = '];';

        if (@file_put_contents($target, implode("\n", $lines)."\n") === false) {
            throw new RuntimeException("Could not write tokens file: {$target}");
        }
    }

    /**
     * @param  array<array-key, string>  $items
     */
    private function inline(array $items): string
    {
        $parts = [];
        foreach ($items as $key => $value) {
            $parts[] = var_export((string) $key, true).' => '.var_export($value, true);
        }

        return '['.implode(', ', $parts).']';
    }

    /**
     * Walks $path into a Style Dictionary document and returns its
     * leaf `value`s keyed by name (hex colours are uppercased).
     *
     * @param  array<string, mixed>  $document
     * @param  list<string>  $path
     * @return array<array-key, string>
     */
    private function leaves(array $document, array $path): array
    {
        $node = $document;
        foreach ($path as $segment) {
            if (! is_array($node) || ! array_key_exists($segment, $node)) {
                throw new RuntimeException('Missing token group "'.implode('.', $path).'" in upstream file.');
            }
            $node = $node[$segment];
        }

        $result = [];
        foreach ((array) $node as $name => $token) {
            if (! is_array($token) || ! isset($token['value']) || ! is_string($token['value'])) {
                throw new RuntimeException('Token "'.implode('.', [...$path, (string) $name]).'" has no string value.');
            }

            $value = $token['value'];
            $result[$name] = preg_match('/^#[0-9a-f]{3,8}$/i', $value) === 1 ? strtoupper($value) : $value;
        }

        return $result;
    }

    /**
     * @return array<string, mixed>
     */
    private function read(string $root, string $relative): array
    {
        $file = rtrim($root, '/').'/'.$relative;

        if (! is_file($file)) {
            throw new RuntimeException("Upstream token file not found: {$file}");
        }

        $decoded = json_decode((string) file_get_contents($file), true);

        if (! is_array($decoded)) {
            throw new RuntimeException("Upstream token file is not valid JSON: {$file}");
        }

        return $decoded;
    }

    private function revision(string $path): string
    {
        $output = [];
        $status = 1;
        exec('git -C '.escapeshellarg($path).' rev-parse HEAD 2>/dev/null', $output, $status);

        $sha = trim($output[0] ?? '');

        if ($status !== 0 || $sha === '') {
            throw new RuntimeException("Could not resolve git revision for: {$path}");
        }

        return $sha;
    }
}
